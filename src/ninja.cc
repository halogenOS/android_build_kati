static size_t FindCommandLineFlag(std::string_view cmd, std::string_view name) {
  const size_t found = cmd.find(name);
  if (found == std::string::npos || found == 0)
    return std::string::npos;
  return found;
}

static std::string_view FindCommandLineFlagWithArg(std::string_view cmd,
                                                   std::string_view name) {
  size_t index = FindCommandLineFlag(cmd, name);
  if (index == std::string::npos)
    return std::string_view();

  std::string_view val = TrimLeftSpace(cmd.substr(index + name.size()));
  index = val.find(name);
  while (index != std::string::npos) {
    val = TrimLeftSpace(val.substr(index + name.size()));
    index = val.find(name);
  }

  index = val.find_first_of(" \t");
  return val.substr(0, index);
}

static bool StripPrefix(std::string_view p, std::string_view* s) {
  if (!HasPrefix(*s, p))
    return false;
  *s = s->substr(p.size());
  return true;
}

size_t GetGomaccPosForAndroidCompileCommand(std::string_view cmdline) {
  size_t index = cmdline.find(' ');
  if (index == std::string::npos)
    return std::string::npos;
  std::string_view cmd = cmdline.substr(0, index);
  if (HasSuffix(cmd, "ccache")) {
    index++;
    size_t pos = GetGomaccPosForAndroidCompileCommand(cmdline.substr(index));
    return pos == std::string::npos ? std::string::npos : pos + index;
  }
  if (!StripPrefix("prebuilts/", &cmd))
    return std::string::npos;
  if (!StripPrefix("gcc/", &cmd) && !StripPrefix("clang/", &cmd))
    return std::string::npos;
  if (!HasSuffix(cmd, "gcc") && !HasSuffix(cmd, "g++") &&
      !HasSuffix(cmd, "clang") && !HasSuffix(cmd, "clang++")) {
    return std::string::npos;
  }

  std::string_view rest = cmdline.substr(index);
  return rest.find(" -c ") != std::string::npos ? 0 : std::string::npos;
}

static std::variant<std::optional<std::string>, DepfileError>
GetDepfileFromCommandImpl(std::string_view cmd) {
  if ((FindCommandLineFlag(cmd, " -MD") == std::string::npos &&
       FindCommandLineFlag(cmd, " -MMD") == std::string::npos) ||
      FindCommandLineFlag(cmd, " -c") == std::string::npos) {
    return std::nullopt;
  }

  std::string_view mf = FindCommandLineFlagWithArg(cmd, " -MF");
  if (!mf.empty()) {
    return std::string(mf);
  }

  std::string_view o = FindCommandLineFlagWithArg(cmd, " -o");
  if (o.empty()) {
    return DepfileError{DepfileError::Cause::kNoDepfileName, std::string(cmd)};
  }

  std::string out(StripExt(o));
  out += ".d";
  return out;
}

std::variant<std::optional<std::string>, DepfileError> GetDepfileFromCommand(
    std::string* cmd) {
  CHECK(!cmd->empty());
  std::variant<std::optional<std::string>, DepfileError> result =
      GetDepfileFromCommandImpl(*cmd);
  std::optional<std::string>* depfile =
      std::get_if<std::optional<std::string>>(&result);
  if (!depfile || !*depfile)
    return result;
  std::string& out = **depfile;

  // A hack for Android - llvm-rs-cc seems not to emit a dep file.
  if (cmd->find("bin/llvm-rs-cc ") != std::string::npos) {
    return std::nullopt;
  }

  // TODO: A hack for Makefiles generated by automake.

  // A hack for Android to get .P files instead of .d.
  std::string p{StripExt(out)};
  p += ".P";
  if (cmd->find(p) != std::string::npos) {
    const std::string rm_f = "; rm -f " + out;
    const size_t found = cmd->find(rm_f);
    if (found == std::string::npos) {
      return DepfileError{DepfileError::Cause::kNoDepfileRemoval, *cmd};
    }
    cmd->erase(found, rm_f.size());
    return result;
  }

  // A hack for Android. For .s files, GCC does not use C
  // preprocessor, so it ignores -MF flag.
  std::string as = "/";
  as.append(StripExt(Basename(out)));
  as += ".s";
  if (cmd->find(as) != std::string::npos) {
    return std::nullopt;
  }

  *cmd += "&& cp ";
  *cmd += out;
  *cmd += ' ';
  *cmd += out;
  *cmd += ".tmp ";
  out += ".tmp";
  return result;
}

static std::string EscapeNinja(const std::string& s) {
  if (s.find_first_of("$: ") == std::string::npos)
    return s;
  std::string r;
  for (char c : s) {
    switch (c) {
      case '$':
      case ':':
      case ' ':
        r += '$';
        [[fallthrough]];
      default:
        r += c;
    }
  }
  return r;
}

static std::string EscapeBuildTarget(Symbol s) {
  return EscapeNinja(s.str());
}

struct NinjaNode {
  const DepNode* node;
  std::vector<Command> commands;
  int rule_id;
};

// The shell script of a node's rule, as the Ninja file lists it.
struct RuleScript {
  std::string command;
  std::string description;
  std::optional<std::string> depfile;
  // Whether |command| goes to a response file, unescaped.
  bool in_rspfile;
  bool use_local_pool;
};

// A variable whose value only the main thread may evaluate, and the string the
// value goes to.
struct RuleVar {
  Var* var;
  std::string* value;
};

// Everything the text of one node is made of.
struct NodeParts {
  const DepNode* node;
  int rule_id;
  // Present when the node has commands.
  std::optional<RuleScript> script = std::nullopt;
  // Values of .KATI_NINJA_POOL and .KATI_TAGS.
  std::string pool = "";
  std::string tags = "";

  std::string RuleName() const {
    return script ? StringPrintf("rule%d", rule_id) : "phony";
  }

  bool UsesLocalPool() const { return script && script->use_local_pool; }

  // .KATI_DEPFILE, .KATI_NINJA_POOL and .KATI_TAGS, in the order that the
  // lines setting them appear in the text of the node. A variable the node
  // does not use is null.
  std::array<RuleVar, 3> RuleVars() {
    RuleVar depfile{nullptr, nullptr};
    if (script && node->depfile_var)
      depfile = {node->depfile_var, &*script->depfile};
    return {depfile, RuleVar{node->ninja_pool_var, &pool},
            RuleVar{node->tags_var, &tags}};
  }

  bool NeedsRuleVars() {
    const std::array<RuleVar, 3> vars = RuleVars();
    return std::any_of(vars.begin(), vars.end(),
                       [](const RuleVar& rule_var) { return rule_var.var; });
  }
};

// A node whose text needs values that only the main thread may evaluate.
struct PendingNode {
  // Where the text goes in the text of the chunk that contains the node.
  size_t text_offset;
  NodeParts parts;
  std::string text = "";
};

// Time the workers spent formatting one chunk.
struct FormatTimes {
  // GenShellScript(), TranslateCommand() and EscapeShell().
  double shell_script_seconds = 0;
  // The rest, depfile detection included.
  double node_text_seconds = 0;
};

// Consecutive nodes, which one worker formats.
struct NodeChunk {
  // Freed once formatted.
  std::vector<NinjaNode> nodes;
  // Text of the nodes, without the pending ones.
  std::string text;
  std::vector<PendingNode> pending;
  // Set for the first node that cannot be formatted. The chunk ends before it.
  std::optional<DepfileError> error;
  // Ready once |text|, |pending| and |error| are set.
  std::future<void> nodes_done;
  // Ready once every pending node has its text. Not set without pending nodes.
  std::future<void> pending_done;
  FormatTimes times;
};

// Formats the text of nodes the main thread evaluated. The worker threads share
// it, so it only reads, and it has no access to the evaluator.
class NodeFormatter {
 public:
  NodeFormatter(std::string shell,
                std::string shell_flags,
                bool use_goma,
                std::string gomacc)
      : shell_(std::move(shell)),
        shell_flags_(std::move(shell_flags)),
        use_goma_(use_goma),
        gomacc_(std::move(gomacc)) {}

  void FormatNodes(NodeChunk* chunk) const {
    std::ostringstream out;
    StepTimer timer;
    for (const NinjaNode& nn : chunk->nodes) {
      NodeParts parts{nn.node, nn.rule_id};
      if (!nn.commands.empty()) {
        chunk->error =
            GenRuleScript(nn, &parts.script.emplace(), &timer, &chunk->times);
        if (chunk->error) {
          break;
        }
      }
      if (parts.NeedsRuleVars()) {
        const size_t offset = static_cast<size_t>(out.tellp());
        chunk->pending.push_back({offset, std::move(parts)});
      } else {
        EmitNode(parts, out);
      }
      timer.Lap(&chunk->times.node_text_seconds);
    }
    chunk->text = out.str();
    chunk->nodes = std::vector<NinjaNode>();
  }

  // Runs after the main thread evaluated the rule variables.
  void FormatPendingNodes(NodeChunk* chunk) const {
    StepTimer timer;
    for (PendingNode& pending : chunk->pending) {
      std::ostringstream out;
      EmitNode(pending.parts, out);
      pending.text = out.str();
      // The text is all that is needed of the node from here on.
      pending.parts.script.reset();
      pending.parts.pool.clear();
      pending.parts.tags.clear();
    }
    timer.Lap(&chunk->times.node_text_seconds);
  }

 private:
  std::string_view TranslateCommand(const char* in,
                                    std::string* cmd_buf) const {
    const size_t orig_size = cmd_buf->size();
    bool prev_backslash = false;
    // Set space as an initial value so the leading comment will be
    // stripped out.
    char prev_char = ' ';
    char quote = 0;
    for (; *in; in++) {
      switch (*in) {
        case '#':
          if (quote == 0 && isspace(prev_char)) {
            while (in[1] && *in != '\n')
              in++;
          } else {
            *cmd_buf += *in;
          }
          break;

        case '\'':
        case '"':
        case '`':
          if (quote) {
            if (quote == *in)
              quote = 0;
          } else if (!prev_backslash) {
            quote = *in;
          }
          *cmd_buf += *in;
          break;

        case '$':
          *cmd_buf += "$$";
          break;

        case '\n':
          if (prev_backslash) {
            cmd_buf->resize(cmd_buf->size() - 1);
          } else {
            *cmd_buf += ' ';
          }
          break;

        case '\\':
          *cmd_buf += '\\';
          break;

        default:
          *cmd_buf += *in;
      }

      if (*in == '\\') {
        prev_backslash = !prev_backslash;
      } else {
        prev_backslash = false;
      }

      prev_char = *in;
    }

    if (prev_backslash) {
      cmd_buf->resize(cmd_buf->size() - 1);
    }

    while (true) {
      char c = (*cmd_buf)[cmd_buf->size() - 1];
      if (!isspace(c) && c != ';')
        break;
      cmd_buf->resize(cmd_buf->size() - 1);
    }

    return std::string_view(cmd_buf->data() + orig_size,
                            cmd_buf->size() - orig_size);
  }

  bool IsOutputMkdir(const char* name, std::string_view cmd) const {
    if (!HasPrefix(cmd, "mkdir -p ")) {
      return false;
    }
    cmd = cmd.substr(9, cmd.size());
    if (!cmd.empty() && cmd.back() == '/') {
      cmd.remove_suffix(1);
    }

    std::string_view dir = Dirname(name);
    if (cmd == dir) {
      return true;
    }
    return false;
  }

  bool GetDescriptionFromCommand(std::string_view cmd, std::string* out) const {
    if (!HasPrefix(cmd, "echo ")) {
      return false;
    }
    cmd = cmd.substr(5, cmd.size());

    bool prev_backslash = false;
    char quote = 0;
    std::string out_buf;

    // Strip outer quotes, and fail if it is not a single echo command
    for (std::string_view::iterator in = cmd.begin(); in != cmd.end(); in++) {
      if (prev_backslash) {
        prev_backslash = false;
        out_buf += *in;
      } else if (*in == '\\') {
        prev_backslash = true;
        out_buf += *in;
      } else if (quote) {
        if (*in == quote) {
          quote = 0;
        } else {
          out_buf += *in;
        }
      } else {
        switch (*in) {
          case '\'':
          case '"':
          case '`':
            quote = *in;
            break;

          case '<':
          case '>':
          case '&':
          case '|':
          case ';':
            return false;

          default:
            out_buf += *in;
        }
      }
    }

    *out = out_buf;
    return true;
  }

  bool GenShellScript(const char* name,
                      const std::vector<Command>& commands,
                      std::string* cmd_buf,
                      std::string* description) const {
    bool got_descritpion = false;
    bool use_gomacc = false;
    auto command_count = commands.size();
    for (const Command& c : commands) {
      size_t cmd_begin = cmd_buf->size();

      if (!cmd_buf->empty()) {
        *cmd_buf += " && ";
      }

      const char* in = c.cmd.c_str();
      while (isspace(*in))
        in++;

      bool needs_subshell =
          (command_count > 1 || c.ignore_error) && !c.force_no_subshell;

      if (needs_subshell)
        *cmd_buf += '(';

      size_t cmd_start = cmd_buf->size();
      std::string_view translated = TranslateCommand(in, cmd_buf);
      if (g_flags.detect_android_echo && !got_descritpion && !c.echo &&
          GetDescriptionFromCommand(translated, description)) {
        got_descritpion = true;
        translated = std::string_view();
      } else if (IsOutputMkdir(name, translated) && !c.echo && cmd_begin == 0) {
        translated = std::string_view();
      }
      if (translated.empty()) {
        cmd_buf->resize(cmd_begin);
        command_count -= 1;
        continue;
      } else if (g_flags.goma_dir) {
        size_t pos = GetGomaccPosForAndroidCompileCommand(translated);
        if (pos != std::string::npos) {
          cmd_buf->insert(cmd_start + pos, gomacc_);
          use_gomacc = true;
        }
      } else if (translated.find("/gomacc") != std::string::npos) {
        use_gomacc = true;
      }

      if (c.ignore_error) {
        *cmd_buf += " ; true";
      }

      if (needs_subshell)
        *cmd_buf += " )";
    }
    return (use_goma_ || g_flags.remote_num_jobs || g_flags.goma_dir) &&
           !use_gomacc;
  }

  // Fills |script| from the commands of |nn|, and adds the time spent to
  // |times|. Returns why the depfile of a compile command cannot be found.
  std::optional<DepfileError> GenRuleScript(const NinjaNode& nn,
                                            RuleScript* script,
                                            StepTimer* timer,
                                            FormatTimes* times) const {
    const DepNode* node = nn.node;
    script->description = "build $out";
    script->use_local_pool =
        GenShellScript(node->output.c_str(), nn.commands, &script->command,
                       &script->description);
    timer->Lap(&times->shell_script_seconds);
    if (node->depfile_var) {
      // The main thread evaluates the variable into it, see
      // NodeParts::RuleVars().
      script->depfile.emplace();
    } else if (g_flags.detect_depfiles) {
      script->command += ' ';
      std::variant<std::optional<std::string>, DepfileError> depfile =
          GetDepfileFromCommand(&script->command);
      if (DepfileError* error = std::get_if<DepfileError>(&depfile))
        return std::move(*error);
      script->command.resize(script->command.size() - 1);
      script->depfile =
          std::get<std::optional<std::string>>(std::move(depfile));
    }
    timer->Lap(&times->node_text_seconds);

    // The limit is about 130kB on Linux and about 250kB on macOS.
    // TODO: Find this number automatically.
    script->in_rspfile = script->command.size() > 100 * 1000;
    if (!script->in_rspfile)
      EscapeShell(&script->command);
    timer->Lap(&times->shell_script_seconds);
    return std::nullopt;
  }

  void EmitNode(const NodeParts& parts, std::ostream& out) const {
    const DepNode* node = parts.node;

    if (g_flags.enable_debug) {
      out << "# " << (node->loc.filename ? node->loc.filename : "(null)") << ':'
          << node->loc.lineno << "\n";
    }
    if (parts.script) {
      const RuleScript& script = *parts.script;
      out << "rule " << parts.RuleName() << "\n";

      out << " description = " << script.description << "\n";
      if (script.depfile) {
        out << " depfile = " << *script.depfile << "\n";
        out << " deps = gcc\n";
      }

      if (script.in_rspfile) {
        out << " rspfile = $out.rsp\n";
        out << " rspfile_content = " << script.command << "\n";
        out << " command = " << shell_ << " $out.rsp\n";
      } else {
        out << " command = " << shell_ << ' ' << shell_flags_ << " \""
            << script.command << "\"\n";
      }
      if (node->is_restat) {
        out << " restat = 1\n";
      }
    }

    EmitBuild(parts, out);
  }

  void EmitBuild(const NodeParts& parts, std::ostream& out) const {
    const DepNode* node = parts.node;
    std::string target = EscapeBuildTarget(node->output);
    out << "build " << target;
    if (!node->implicit_outputs.empty()) {
      out << " |";
      for (Symbol output : node->implicit_outputs) {
        out << " " << EscapeBuildTarget(output);
      }
    }
    out << ": " << parts.RuleName();
    std::vector<Symbol> order_onlys;
    if (node->is_phony && !g_flags.use_ninja_phony_output) {
      out << " _kati_always_build_";
    }
    for (auto const& d : node->deps) {
      out << " " << EscapeBuildTarget(d.first).c_str();
    }
    if (!node->order_onlys.empty()) {
      out << " ||";
      for (auto const& d : node->order_onlys) {
        out << " " << EscapeBuildTarget(d.first).c_str();
      }
    }
    if (!node->validations.empty()) {
      out << " |@";
      for (auto const& d : node->validations) {
        out << " " << EscapeBuildTarget(d.first).c_str();
      }
    }

    out << "\n";

    if (parts.pool != "") {
      if (parts.pool != "none") {
        out << " pool = " << parts.pool << "\n";
      }
    } else if (g_flags.default_pool && parts.script) {
      out << " pool = " << g_flags.default_pool << "\n";
    } else if (parts.UsesLocalPool()) {
      out << " pool = local_pool\n";
    }
    if (node->is_phony && g_flags.use_ninja_phony_output) {
      out << " phony_output = true\n";
    }
    if (!parts.tags.empty()) {
      out << " tags = " << parts.tags << "\n";
    }
  }

  const std::string shell_;
  const std::string shell_flags_;
  const bool use_goma_;
  const std::string gomacc_;
};

// Where the time of Ninja generation went, for --kati_stats.
struct NinjaGenerationTimes {
  // Summed over the workers.
  double shell_script_seconds = 0;
  double node_text_seconds = 0;
  // Spent by the main thread.
  double rule_var_seconds = 0;
  double wait_seconds = 0;
  // Spent by the writers of the Ninja file.
  double write_seconds = 0;

  void Report() const {
    LOG_STAT("ninja gen (format shell scripts, all workers): %f",
             shell_script_seconds);
    LOG_STAT("ninja gen (format node text, all workers): %f",
             node_text_seconds);
    LOG_STAT("ninja gen (rule variables): %f", rule_var_seconds);
    LOG_STAT("ninja gen (write): %f", write_seconds);
    LOG_STAT("ninja gen (write wait for chunk): %f", wait_seconds);
  }
};

// The result of writing the Ninja file.
struct NinjaFileWrite {
  std::error_code error;
  double seconds = 0;
};

class NinjaGenerator {
 public:
  NinjaGenerator(Evaluator* ev, double start_time)
      : ce_(ev),
        ev_(ev),
        rule_id_(0),
        kati_binary_(GetExecutablePath()),
        start_time_(start_time),
        default_target_(NULL),
        // With the main thread, as many threads run as Kati may use CPUs.
        workers_(std::max(1, StartCpuCount() - 1), SetStartAffinity) {
    std::string shell = EscapeNinja(ev->GetShell());
    std::string shell_flags = EscapeNinja(ev->GetShellFlag());
    ev_->set_avoid_io(true);
    const std::string use_goma_str = ev->EvalVar(Intern("USE_GOMA"));
    const bool use_goma = !(use_goma_str.empty() || use_goma_str == "false");
    std::string gomacc;
    if (g_flags.goma_dir)
      gomacc = StringPrintf("%s/gomacc ", g_flags.goma_dir);
    formatter_ = std::make_unique<const NodeFormatter>(
        std::move(shell), std::move(shell_flags), use_goma, std::move(gomacc));
  }

  ~NinjaGenerator() { ev_->set_avoid_io(false); }

  void Generate(const std::vector<NamedDepNode>& nodes,
                const std::string& orig_args) {
    unlink(GetNinjaStampFilename().c_str());
    PopulateNinjaNodes(nodes);
    GenerateNinja();
    GenerateShell();
    GenerateStamp(orig_args);
    FinishNinjaFile();
    if (rename(GetStampTempFilename().c_str(),
               GetNinjaStampFilename().c_str()) != 0) {
      PERROR("rename(%s) failed", GetStampTempFilename().c_str());
    }
  }

  static std::string GetStampTempFilename() {
    return GetFilename(".kati_stamp%s.tmp");
  }

  static std::string GetFilename(const char* fmt) {
    std::string r = g_flags.ninja_dir ? g_flags.ninja_dir : ".";
    r += '/';
    r += StringPrintf(fmt, g_flags.ninja_suffix ? g_flags.ninja_suffix : "");
    return r;
  }

 private:
  // Workers get the formatter only, as what the generator does needs the
  // evaluator, which is not thread-safe.
  void CheckOnMainThread() const {
    CHECK(std::this_thread::get_id() == main_thread_);
  }

  void PopulateNinjaNodes(const std::vector<NamedDepNode>& nodes) {
    ScopedTimeReporter tr("ninja gen (eval)");
    for (auto const& [symbol, depnode] : nodes) {
      PopulateNinjaNode(*depnode);
    }
    CloseChunk();
  }

  // Hands the nodes populated since the last call to the workers.
  void CloseChunk() {
    CheckOnMainThread();
    if (chunk_nodes_.empty() || g_flags.generate_empty_ninja)
      return;
    NodeChunk& chunk = chunks_.emplace_back();
    chunk.nodes = std::move(chunk_nodes_);
    chunk_nodes_.clear();
    chunk.nodes_done = workers_.Run([formatter = formatter_.get(), &chunk] {
      formatter->FormatNodes(&chunk);
    });
  }

  void PopulateNinjaNode(const DepNode& node) {
    CheckOnMainThread();
    if (done_.exists(node.output)) {
      return;
    }
    done_.insert(node.output);
    ScopedFrame frame(
        ce_.evaluator()->Enter(FrameType::NINJA, node.output.str(), node.loc));

    // A hack to exclude out phony target in Android. If this exists,
    // "ninja -t clean" tries to remove this directory and fails.
    if (g_flags.detect_android_echo && node.output.str() == "out")
      return;

    // This node is a leaf node
    if (!node.has_rule && !node.is_phony) {
      return;
    }

    std::vector<Command> commands = ce_.Eval(node);
    const int rule_id = commands.empty() ? -1 : rule_id_++;
    if (!IsSpecialTarget(node.output)) {
      chunk_nodes_.push_back({&node, std::move(commands), rule_id});
      if (node.is_default_target)
        default_target_ = &node;
      // A worker is idle when no task is queued, so it takes the chunk now.
      if (!workers_.HasQueuedTasks())
        CloseChunk();
    }

    for (auto const& [symbol, depnode] : node.deps) {
      PopulateNinjaNode(*depnode);
    }
    for (auto const& [symbol, depnode] : node.order_onlys) {
      PopulateNinjaNode(*depnode);
    }
    for (auto const& [symbol, depnode] : node.validations) {
      PopulateNinjaNode(*depnode);
    }
  }

  void EvalRuleVars(NodeParts* parts) {
    CheckOnMainThread();
    for (const RuleVar& rule_var : parts->RuleVars()) {
      if (rule_var.var)
        rule_var.var->Eval(ev_, rule_var.value);
    }
  }

  static void ReportDepfileError(const DepfileError& error) {
    switch (error.cause) {
      case DepfileError::Cause::kNoDepfileName:
        ERROR("Cannot find the depfile in %s", error.command.c_str());
        break;
      case DepfileError::Cause::kNoDepfileRemoval:
        ERROR("Cannot find removal of .d file: %s", error.command.c_str());
        break;
    }
  }

  static std::string GetEnvScriptFilename() { return GetFilename("env%s.sh"); }

  void GenerateNinja() {
    ScopedTimeReporter tr("ninja gen (emit)");
    std::ostringstream out;
    out << "# Generated by kati " << kGitVersion << "\n\n";

    if (!used_envs_.empty()) {
      out << "# Environment variables used:\n";
      for (const auto& [key, value] : used_envs_) {
        out << "# " << key << "=" << value << '\n';
      }
      out << '\n';
    }

    if (!g_flags.no_ninja_prelude) {
      if (g_flags.ninja_dir) {
        out << "builddir = " << g_flags.ninja_dir << "\n\n";
      }

      out << "pool local_pool\n"
          << " depth = " << g_flags.num_jobs << "\n\n";

      if (!g_flags.use_ninja_phony_output) {
        out << "build _kati_always_build_: phony\n\n";
      }
    }

    ninja_header_ = out.str();

    if (!g_flags.generate_empty_ninja) {
      ScheduleRuleVariables(&times_);
      WaitForPendingNodes(&times_);

      std::string default_targets;
      if (g_flags.targets.empty() || g_flags.gen_all_targets) {
        CHECK(default_target_);
        default_targets = EscapeBuildTarget(default_target_->output);
      } else {
        for (Symbol s : g_flags.targets) {
          if (!default_targets.empty())
            default_targets += ' ';
          default_targets += EscapeBuildTarget(s);
        }
      }
      ninja_footer_ = "\ndefault " + default_targets + '\n';
    }

    ninja_write_done_ = workers_.Run([pieces = NinjaFilePieces()] {
      StepTimer timer;
      NinjaFileWrite write{WriteFileInParallel(GetNinjaFilename(), pieces)};
      timer.Lap(&write.seconds);
      return write;
    });

    SymbolSet used_env_vars(Vars::used_env_vars());
    // PATH changes $(shell).
    used_env_vars.insert(Intern("PATH"));
    for (Symbol e : used_env_vars) {
      std::string_view val(getenv(e.c_str()));
      used_envs_.emplace(e.str(), std::string(val));
    }
  }

  // Evaluates the rule variables of the pending nodes in node order, and hands
  // each chunk back to the workers to format them. Stops Kati at the first node
  // that cannot be formatted.
  void ScheduleRuleVariables(NinjaGenerationTimes* times) {
    StepTimer timer;
    for (NodeChunk& chunk : chunks_) {
      chunk.nodes_done.get();
      timer.Lap(&times->wait_seconds);
      for (PendingNode& pending : chunk.pending) {
        EvalRuleVars(&pending.parts);
      }
      timer.Lap(&times->rule_var_seconds);
      if (chunk.error) {
        ReportDepfileError(*chunk.error);
      }
      if (!chunk.pending.empty()) {
        chunk.pending_done =
            workers_.Run([formatter = formatter_.get(), &chunk] {
              formatter->FormatPendingNodes(&chunk);
            });
      }
    }
  }

  void WaitForPendingNodes(NinjaGenerationTimes* times) {
    StepTimer timer;
    for (NodeChunk& chunk : chunks_) {
      if (!chunk.pending.empty()) {
        chunk.pending_done.get();
      }
      times->shell_script_seconds += chunk.times.shell_script_seconds;
      times->node_text_seconds += chunk.times.node_text_seconds;
    }
    timer.Lap(&times->wait_seconds);
  }

  // The text of the Ninja file in order: the header, the chunks with the text
  // of each pending node at its offset, and the footer.
  std::vector<std::string_view> NinjaFilePieces() const {
    std::vector<std::string_view> pieces = {ninja_header_};
    for (const NodeChunk& chunk : chunks_) {
      const std::string_view text = chunk.text;
      size_t written = 0;
      for (const PendingNode& pending : chunk.pending) {
        pieces.push_back(text.substr(written, pending.text_offset - written));
        pieces.push_back(pending.text);
        written = pending.text_offset;
      }
      pieces.push_back(text.substr(written));
    }
    pieces.push_back(ninja_footer_);
    return pieces;
  }

  void FinishNinjaFile() {
    const NinjaFileWrite write = ninja_write_done_.get();
    times_.write_seconds = write.seconds;
    times_.Report();
    if (write.error) {
      ERROR("*** write %s: %s", GetNinjaFilename().c_str(),
            write.error.message().c_str());
    }
  }

  void GenerateShell() {
    FILE* fp = fopen(GetEnvScriptFilename().c_str(), "wb");
    if (fp == NULL)
      PERROR("fopen(env.sh) failed");

    fprintf(fp, "#!/bin/sh\n");
    fprintf(fp, "# Generated by kati %s\n", kGitVersion);
    fprintf(fp, "\n");

    for (const auto& [symbol, is_exported] : ev_->exports()) {
      if (is_exported) {
        const std::string val = ev_->EvalVar(symbol);
        fprintf(fp, "export '%s'='%s'\n", symbol.c_str(), val.c_str());
      } else {
        fprintf(fp, "unset '%s'\n", symbol.c_str());
      }
    }

    if (fclose(fp) != 0)
      PERROR("fclose(env.sh) failed");

    fp = fopen(GetNinjaShellScriptFilename().c_str(), "wb");
    if (fp == NULL)
      PERROR("fopen(ninja.sh) failed");

    fprintf(fp, "#!/bin/sh\n");
    fprintf(fp, "# Generated by kati %s\n", kGitVersion);
    fprintf(fp, "\n");

    fprintf(fp, ". %s\n", GetEnvScriptFilename().c_str());

    fprintf(fp, "exec ninja -f %s ", GetNinjaFilename().c_str());
    if (g_flags.remote_num_jobs > 0) {
      fprintf(fp, "-j%d ", g_flags.remote_num_jobs);
    } else if (g_flags.goma_dir) {
      fprintf(fp, "-j500 ");
    }
    fprintf(fp, "\"$@\"\n");

    if (fclose(fp) != 0)
      PERROR("fclose(ninja.sh) failed");

    if (chmod(GetNinjaShellScriptFilename().c_str(), 0755) != 0)
      PERROR("chmod ninja.sh failed");
  }

  void GenerateStamp(const std::string& orig_args) {
    BufferedOutputFile stamp(GetStampTempFilename());
    FILE* fp = stamp.fp();

    size_t r = fwrite(&start_time_, sizeof(start_time_), 1, fp);
    CHECK(r == 1);

    std::unordered_set<std::string> makefiles;
    MakefileCacheManager::Get().GetAllFilenames(&makefiles);
    DumpInt(fp, makefiles.size() + 1);
    DumpString(fp, kati_binary_);
    for (const std::string& makefile : makefiles) {
      DumpString(fp, makefile);
    }

    DumpInt(fp, Evaluator::used_undefined_vars().size());
    for (Symbol v : Evaluator::used_undefined_vars()) {
      DumpString(fp, v.str());
    }
    DumpInt(fp, used_envs_.size());
    for (const auto& [key, value] : used_envs_) {
      DumpString(fp, key);
      DumpString(fp, value);
    }

    auto& globs = GetAllGlobCache();
    DumpInt(fp, globs.size());
    for (const auto& [key, files] : globs) {
      DumpString(fp, key);
#if 0
      std::unordered_set<std::string> dirs;
      GetReadDirs(p.first, files, &dirs);
      DumpInt(fp, dirs.size());
      for (const std::string& dir : dirs) {
        DumpString(fp, dir);
      }
#endif
      DumpInt(fp, files.size());
      for (const std::string& file : files) {
        DumpString(fp, file);
      }
    }

    const std::vector<CommandResult*>& crs = GetShellCommandResults();
    DumpInt(fp, crs.size());
    for (CommandResult* cr : crs) {
      DumpInt(fp, static_cast<int>(cr->op));
      DumpString(fp, cr->shell);
      DumpString(fp, cr->shellflag);
      DumpString(fp, cr->cmd);
      DumpString(fp, cr->result);
      DumpString(fp, cr->loc.filename);
      DumpInt(fp, cr->loc.lineno);

      if (cr->op == CommandOp::FIND) {
        std::vector<std::string> missing_dirs;
        for (std::string_view fd : cr->find->finddirs) {
          const std::string& d = ConcatDir(cr->find->chdir, fd);
          if (!Exists(d))
            missing_dirs.push_back(d);
        }
        DumpInt(fp, missing_dirs.size());
        for (const std::string& d : missing_dirs) {
          DumpString(fp, d);
        }

        DumpInt(fp, cr->find->found_files->size());
        for (std::string_view s : *cr->find->found_files) {
          DumpString(fp, ConcatDir(cr->find->chdir, s));
        }

        DumpInt(fp, cr->find->read_dirs->size());
        for (std::string_view s : *cr->find->read_dirs) {
          DumpString(fp, ConcatDir(cr->find->chdir, s));
        }
      }
    }

    DumpString(fp, orig_args);

    if (const std::error_code error = stamp.Close()) {
      ERROR("*** write %s: %s", GetStampTempFilename().c_str(),
            error.message().c_str());
    }
  }

  const std::thread::id main_thread_ = std::this_thread::get_id();
  CommandEvaluator ce_;
  Evaluator* ev_;
  SymbolSet done_;
  int rule_id_;
  std::map<std::string, std::string> used_envs_;
  const std::string kati_binary_;
  const double start_time_;
  // Nodes populated since the last chunk closed.
  std::vector<NinjaNode> chunk_nodes_;
  const DepNode* default_target_;
  std::unique_ptr<const NodeFormatter> formatter_;
  std::deque<NodeChunk> chunks_;
  // The text of the Ninja file before and after the chunks.
  std::string ninja_header_;
  std::string ninja_footer_;
  std::future<NinjaFileWrite> ninja_write_done_;
  NinjaGenerationTimes times_;
  // Declared last, so the workers stop before the chunks they format and the
  // formatter go away.
  ThreadPool workers_;
};

std::string GetNinjaFilename() {
  return NinjaGenerator::GetFilename("build%s.ninja");
}

std::string GetNinjaShellScriptFilename() {
  return NinjaGenerator::GetFilename("ninja%s.sh");
}

std::string GetNinjaStampFilename() {
  return NinjaGenerator::GetFilename(".kati_stamp%s");
}

void GenerateNinja(const std::vector<NamedDepNode>& nodes,
                   Evaluator* ev,
                   const std::string& orig_args,
                   double start_time) {
  NinjaGenerator ng(ev, start_time);
  ng.Generate(nodes, orig_args);
}
